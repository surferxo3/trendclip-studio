"""Build a safe original briefing from a selected discovery candidate."""

from __future__ import annotations

import re
import tempfile
import textwrap
from datetime import date, datetime, timezone
from pathlib import Path
from typing import Dict, List

from .config import Scene, TopicConfig, validate_date, validate_slug
from .render import render_clip, write_metadata
from .validate import add_content_quality, inspect_media_quality, probe_video, write_validation


SAFE_TEXT = re.compile(r"[^A-Z0-9 +|/:,?-]")


def _safe_text(value: str) -> str:
    value = value.upper().replace("&", " AND ").replace("—", "-").replace("’", "")
    return re.sub(r"\s+", " ", SAFE_TEXT.sub("", value)).strip()


def _headline(value: str, width: int = 18, lines: int = 3) -> str:
    wrapped = textwrap.wrap(_safe_text(value), width=width, break_long_words=True, break_on_hyphens=False)
    if not wrapped:
        return "OFFICIAL UPDATE"
    if len(wrapped) > lines:
        wrapped = wrapped[:lines]
        wrapped[-1] = wrapped[-1][: max(1, width - 1)].rstrip() + "-"
    return "\n".join(wrapped)


def _source_label(value: str) -> str:
    cleaned = _safe_text(value).replace("OFFICIAL YOUTUBE", "").strip(" -")
    return (cleaned or "OFFICIAL SOURCE")[:30]


def config_from_candidate(base: TopicConfig, candidate: Dict[str, object], output_date: str) -> TopicConfig:
    validate_date(output_date)
    title = str(candidate.get("title", "Official update"))
    url = str(candidate.get("url", ""))
    source_name = str(candidate.get("source_name", "Official source"))
    published_at = str(candidate.get("published_at", ""))
    published_date = published_at[:10] if len(published_at) >= 10 else output_date
    source = _source_label(source_name)
    headline = _headline(title)
    scenes: List[Scene] = [
        Scene("LATEST OFFICIAL UPDATE", headline, f"SOURCE: {source}"[:45], 3.6, "#07111F", "#FF4FA3"),
        Scene("STORY SELECTED", "CURRENT\nAND VERIFIED", f"PUBLISHED {published_date}"[:45], 3.6, "#12172A", "#4FE4D4"),
        Scene("SOURCE CHECK", "OFFICIAL\nPUBLISHER FEED", "EVIDENCE LINK SAVED WITH EXPORT", 3.6, "#211127", "#FFB43B"),
        Scene("BEFORE YOU POST", "REVIEW THE\nSOURCE", "VERIFY CONTEXT RIGHTS AND PLATFORM RULES", 3.6, "#0B2530", "#75ED91"),
        Scene("CONTENT DISCLOSURE", "ORIGINAL\nNEWS BRIEF", "NO REUSED VIDEO OR COMMERCIAL MUSIC", 3.6, "#090B12", "#FF4FA3"),
    ]
    metadata = {
        "suggested_title": f"{title} — Quick Official Update",
        "description": f"An original graphical briefing based on the selected official-source update: {title}. Review the linked source before uploading.",
        "hashtags": ["#GTAVI", "#GrandTheftAutoVI", "#RockstarGames", "#GamingNews", "#Shorts"],
        "content_type": "original graphical briefing generated from a selected official-source candidate",
        "content_disclosure": "Original graphical briefing; no source video, gameplay, trailer footage, or commercial music is reused.",
        "source_references": [
            {
                "title": title,
                "url": url,
                "publisher": source_name,
                "retrieved_at": output_date,
                "supports": ["Selected candidate title", "Publication timestamp", "Official-source attribution"],
            }
        ],
        "asset_provenance": [
            "All visuals are programmatically generated by TrendClip Studio.",
            "Audio is an original two-tone synthetic bed generated locally by FFmpeg.",
            "Typography uses TrendClip Studio's embedded block typeface.",
            "The source video itself is not downloaded, clipped, or redistributed.",
        ],
        "usage_rights_review_status": "Original visual/audio assets only. Human review is still required before upload; source attribution does not grant rights to reuse source media.",
        "selected_candidate": {
            "title": title,
            "url": url,
            "published_at": published_at,
            "source_name": source_name,
            "score": candidate.get("score"),
        },
    }
    return TopicConfig(
        slug=base.slug,
        topic_name=base.topic_name,
        language=base.language,
        keywords=base.keywords,
        exclusions=base.exclusions,
        mode="original",
        width=base.width,
        height=base.height,
        fps=base.fps,
        transition=base.transition,
        scenes=scenes,
        metadata=metadata,
    )


def render_candidate(root: Path, topic_slug: str, candidate: Dict[str, object], output_date: str) -> Dict[str, object]:
    from .cli import promote_export
    from .config import load_topic

    topic_slug = validate_slug(topic_slug)
    output_date = validate_date(output_date)
    base = load_topic(root / "config" / "topics" / f"{topic_slug}.json")
    config = config_from_candidate(base, candidate, output_date)
    destination = root / "output" / topic_slug / output_date
    destination.mkdir(parents=True, exist_ok=True)
    final_video = destination / "clip-001.mp4"
    with tempfile.TemporaryDirectory(prefix=".trendclip-candidate-", dir=destination) as staging_value:
        staging = Path(staging_value)
        staged_video = staging / "clip-001.mp4"
        details = render_clip(config, staged_video)
        validation = add_content_quality(
            probe_video(staged_video, expected_fps=config.fps),
            inspect_media_quality(staged_video, allow_static=True, allow_silence=True),
        )
        if not validation.get("valid"):
            raise RuntimeError("candidate video failed technical validation; prior export was preserved")
        write_validation(validation, staging / "validation.json")
        write_metadata(config, staging / "clip-001.json", final_video, details, validation)
        promote_export(staging, destination)
    return {
        "video": str(final_video),
        "validation": validation,
        "generated_at": datetime.now(timezone.utc).isoformat(),
    }

